def summarize_per_run_metrics(per_run: pd.DataFrame, metrics: list[str]) -> pd.DataFrame:
    per_run = per_run[per_run["policy_tag"].isin(POLICY_ORDER)].copy()
    rows: list[dict[str, float | str]] = []
    for policy_tag in POLICY_ORDER:
        policy_rows = per_run[per_run["policy_tag"] == policy_tag]
        if policy_rows.empty:
            continue
        row: dict[str, float | str] = {
            "policy_tag": policy_tag,
            "alpha": policy_alpha(policy_tag),
        }
        for metric in metrics:
            if metric not in policy_rows.columns:
                raise KeyError(f"Missing expected per-run column {metric}")
            values = (
                pd.to_numeric(policy_rows[metric], errors="coerce")
                .replace([np.inf, -np.inf], np.nan)
                .dropna()
            )
            row[f"{metric}_mean"] = float(values.mean()) if len(values) else np.nan
            row[f"{metric}_std"] = float(values.std(ddof=1)) if len(values) > 1 else 0.0
        rows.append(row)
    return pd.DataFrame(rows)


