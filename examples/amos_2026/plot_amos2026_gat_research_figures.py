def _plot_gaussian_reward_scatter(
    per_run: pd.DataFrame,
    out_dir: Path,
    *,
    x_metric: str,
    x_label: str,
    stem: str,
    colorbar: bool,
    x_divisor: float = 1.0,
    selected_only: bool = False,
) -> None:
    """Plot per-policy reward populations with two-sigma covariance ellipses."""
    cmap = plt.get_cmap(COLORMAP)
    norm = Normalize(0.0, 1.0)
    selected_alphas = {0.0, 0.1, 0.5, 0.75, 1.0}

    data = per_run.copy()
    data["alpha"] = data["policy_tag"].map(policy_alpha)
    data["scatter_x"] = pd.to_numeric(data[x_metric], errors="coerce") / x_divisor
    data["scatter_y"] = pd.to_numeric(
        data["score_ground_value_100d00i"], errors="coerce"
    )
    data = data[np.isfinite(data["scatter_x"]) & np.isfinite(data["scatter_y"])]
    if selected_only:
        data = data[data["alpha"].isin(selected_alphas)].copy()

    fig, ax = plt.subplots(figsize=(8.35, 5.0), constrained_layout=True)
    ax.scatter(
        data["scatter_x"],
        data["scatter_y"],
        c=data["alpha"],
        cmap=cmap,
        norm=norm,
        s=21,
        alpha=0.68,
        edgecolor="none",
        zorder=2,
    )

    stats_rows: list[dict[str, float | int | str]] = []
    for policy_tag in POLICY_ORDER:
        group = data[data["policy_tag"] == policy_tag]
        if group.empty:
            continue
        alpha = policy_alpha(policy_tag)
        color = cmap(norm(alpha))
        xvals = group["scatter_x"].to_numpy(dtype=float)
        yvals = group["scatter_y"].to_numpy(dtype=float)
        mean_x = float(np.mean(xvals))
        mean_y = float(np.mean(yvals))
        std_x = float(np.std(xvals, ddof=1)) if len(group) > 1 else 0.0
        std_y = float(np.std(yvals, ddof=1)) if len(group) > 1 else 0.0
        corr = (
            float(np.corrcoef(xvals, yvals)[0, 1])
            if len(group) > 1 and std_x > 0 and std_y > 0
            else np.nan
        )
        stats_rows.append(
            {
                "policy_tag": policy_tag,
                "alpha": alpha,
                "x_mean": mean_x,
                "x_std": std_x,
                "ground_reward_mean": mean_y,
                "ground_reward_std": std_y,
                "x_reward_corr": corr,
                "n_runs": int(len(group)),
            }
        )

        if len(group) >= 3 and std_x > 0 and std_y > 0:
            cov = np.cov(np.column_stack([xvals, yvals]), rowvar=False)
            eigvals, eigvecs = np.linalg.eigh(cov)
            order = eigvals.argsort()[::-1]
            eigvals = eigvals[order]
            eigvecs = eigvecs[:, order]
            angle = math.degrees(math.atan2(eigvecs[1, 0], eigvecs[0, 0]))
            width, height = 4.0 * np.sqrt(np.maximum(eigvals, 0.0))
            ax.add_patch(
                Ellipse(
                    (mean_x, mean_y),
                    width=width,
                    height=height,
                    angle=angle,
                    facecolor="none",
                    edgecolor=color,
                    linewidth=1.65,
                    alpha=0.9,
                    zorder=3,
                )
            )

        # Smaller than the original population markers so overlapping means remain legible.
        ax.scatter(
            mean_x,
            mean_y,
            marker="o",
            s=88,
            color=color,
            alpha=1.0,
            edgecolor="k",
            linewidth=0.9,
            zorder=4,
        )
        if selected_only:
            label_offsets = {
                0.0: (8, 8),
                0.1: (8, 15),
                0.5: (8, -2),
                0.75: (8, -15),
                1.0: (8, 8),
            }
            alpha_key = round(alpha, 2)
            alpha_label = f"{alpha_key:.2f}".rstrip("0").rstrip(".")
            ax.annotate(
                alpha_label,
                (mean_x, mean_y),
                xytext=label_offsets.get(alpha_key, (8, 8)),
                textcoords="offset points",
                color=color,
                fontsize=11,
                fontweight="bold",
                bbox={"facecolor": "white", "edgecolor": "none", "alpha": 0.78, "pad": 1.2},
                zorder=5,
            )

    stats = pd.DataFrame(stats_rows).sort_values("alpha")
    stats.to_csv(out_dir / f"{stem}_population_stats.csv", index=False)
    (out_dir / f"{stem}_population_stats.md").write_text(
        "```text\n" + stats.round(4).to_string(index=False) + "\n```\n",
        encoding="utf-8",
    )

    legend_blue = "#2C7BB6"
    mean_handle = Line2D(
        [0],
        [0],
        marker="o",
        color="none",
        markerfacecolor=legend_blue,
        markeredgecolor="k",
        markersize=8,
        label="Policy-population mean",
    )
    ellipse_handle = Line2D(
        [0],
        [0],
        color=legend_blue,
        linewidth=1.65,
        label="2$\\sigma$ covariance outline",
    )
    ax.legend(handles=[mean_handle, ellipse_handle], loc="best", framealpha=0.92)
    ax.set_xlabel(x_label)
    ax.set_ylabel("Ground reward")
    title_prefix = "Selected policies " if selected_only else ""
    ax.set_title(f"{title_prefix}evaluated with $\\alpha = 1.0$")
    finish_axis(ax)
    add_alpha_colorbar(fig, ax, norm, cmap, colorbar)
    save_figure(fig, out_dir, stem)


