def finish_axis(ax: plt.Axes, xlabel: str | None = None) -> None:
    if xlabel:
        ax.set_xlabel(xlabel)
    ax.minorticks_on()
    ax.grid(True, alpha=GRID_ALPHA)
    ax.grid(True, which="minor", alpha=GRID_ALPHA * 0.55)
    ax.xaxis.set_minor_locator(AutoMinorLocator(2))
    for spine in ax.spines.values():
        spine.set_linewidth(1.1)


def save_figure(fig: plt.Figure, out_dir: Path, stem: str) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for ext in ("png", "pdf"):
        fig.savefig(out_dir / f"{stem}.{ext}", bbox_inches="tight", dpi=DPI, pad_inches=0.06)
    plt.close(fig)


def mean_col(df: pd.DataFrame, base: str) -> str:
    col = f"{base}_mean"
    if col not in df.columns:
        raise KeyError(f"Missing expected column {col}")
    return col


def std_col(df: pd.DataFrame, base: str) -> str:
    col = f"{base}_std"
    if col not in df.columns:
        raise KeyError(f"Missing expected column {col}")
    return col


def normalize_summary(summary: pd.DataFrame) -> pd.DataFrame:
    summary = summary.copy()
    summary = summary[summary["policy_tag"].isin(POLICY_ORDER)].copy()
    if "n_runs" in summary.columns:
        summary = summary[pd.to_numeric(summary["n_runs"], errors="coerce").fillna(0) > 0]
    summary["policy_tag"] = pd.Categorical(
        summary["policy_tag"], categories=POLICY_ORDER, ordered=True
    )
    summary = summary.sort_values("policy_tag").reset_index(drop=True)
    summary["alpha"] = summary["policy_tag"].astype(str).map(policy_alpha)
    return summary


def normalize_policy_table(table: pd.DataFrame) -> pd.DataFrame:
    table = table.copy()
    if "policy_tag" not in table.columns:
        return table
    table = table[table["policy_tag"].isin(POLICY_ORDER)].copy()
    table["policy_tag"] = pd.Categorical(
        table["policy_tag"], categories=POLICY_ORDER, ordered=True
    )
    return table.sort_values("policy_tag").reset_index(drop=True)


def read_csv_or_empty(path: Path) -> pd.DataFrame:
    if not path.exists() or path.stat().st_size <= 1:
        return pd.DataFrame()
    return pd.read_csv(path)


def run_detailed_if_needed(
    input_root: Path,
    detailed_dir: Path,
    expected_seeds: str,
    storage_capacity_images: float,
    force: bool,
) -> None:
    required = [
        detailed_dir / "detailed_per_run.csv",
        detailed_dir / "detailed_summary_by_policy.csv",
        detailed_dir / "action_distribution_by_policy.csv",
        detailed_dir / "downlink_summary_by_policy.csv",
        detailed_dir / "action_id_distribution_by_policy.csv",
        detailed_dir / "image_candidate_slot_summary_by_policy.csv",
        detailed_dir / "metric_definitions.json",
    ]
    if not force and all(path.exists() for path in required):
        print(f"Reusing detailed analysis in {detailed_dir}")
        return

    script = Path(__file__).with_name("analyze_gat_reward_sweep_mc_detailed.py")
    cmd = [
        sys.executable,
        str(script),
        "--input-root",
        str(input_root),
        "--output-dir",
        str(detailed_dir),
        "--expected-seeds",
        expected_seeds,
        "--storage-capacity-images",
        str(storage_capacity_images),
    ]
    print("Running detailed analyzer:")
    print(" ".join(cmd))
    subprocess.run(cmd, check=True)


def add_alpha_colorbar(fig: plt.Figure, ax: plt.Axes, norm: Normalize, cmap, enabled: bool) -> None:
    if not enabled:
        return
    sm = plt.cm.ScalarMappable(norm=norm, cmap=cmap)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=ax, pad=0.035, fraction=0.04)
    cbar.set_label(r"Downlink reward weight $\alpha$", labelpad=8)


def plot_alpha_metric(
    summary: pd.DataFrame,
    out_dir: Path,
    metric: str,
    ylabel: str,
    stem: str,
    marker: str = "o",
    title: str | None = None,
    ylim: tuple[float, float] | None = None,
    colorbar: bool = True,
) -> None:
    cmap = plt.get_cmap(COLORMAP)
    norm = Normalize(0.0, 1.0)
    x = summary["alpha"].to_numpy(dtype=float)
    y = summary[mean_col(summary, metric)].to_numpy(dtype=float)
    ystd = summary[std_col(summary, metric)].to_numpy(dtype=float)

    fig, ax = plt.subplots(figsize=(7.6, 4.55), constrained_layout=True)
    ax.fill_between(x, y - ystd, y + ystd, color="tab:blue", alpha=FILL_ALPHA, zorder=1)
    ax.errorbar(
        x,
        y,
        yerr=ystd,
        fmt="none",
        ecolor="0.2",
        elinewidth=1.45,
        capsize=CAPSIZE,
        alpha=ERRORBAR_ALPHA,
        zorder=3,
    )
    ax.plot(x, y, color="0.18", linewidth=1.1, alpha=0.45, zorder=2)
    ax.scatter(
        x,
        y,
        c=x,
        cmap=cmap,
        norm=norm,
        marker=marker,
        s=92 if marker != "*" else 170,
        edgecolor="k",
        linewidth=0.8,
        zorder=4,
    )
    if title:
        ax.set_title(title)
    elif metric == "score_ground_value_100d00i":
        ax.set_title(r"Evaluated with $\alpha = 1.0$")
    elif metric == "mean_est_images_removed_per_storage_downlink":
        ax.set_title("Per successful storage-reducing downlink")
    ax.set_ylabel(ylabel)
    ax.set_xlim(-0.025, 1.025)
    if ylim:
        ax.set_ylim(*ylim)
    finish_axis(ax, r"Downlink reward weight $\alpha$")
    add_alpha_colorbar(fig, ax, norm, cmap, colorbar)
    save_figure(fig, out_dir, stem)


def plot_ground_value_score_boxplot(
    per_run: pd.DataFrame, out_dir: Path, colorbar: bool
) -> None:
    required = {"policy_tag", "score_ground_value_100d00i"}
    if per_run.empty or not required.issubset(per_run.columns):
        return

    data = per_run[per_run["policy_tag"].isin(POLICY_ORDER)].copy()
    if "state" in data.columns:
        data = data[data["state"] == "completed"].copy()
    cmap = plt.get_cmap(COLORMAP)
    norm = Normalize(0.0, 1.0)

    values = []
    positions = []
    alphas = []
    for policy_tag in POLICY_ORDER:
        policy_values = (
            pd.to_numeric(
                data.loc[data["policy_tag"] == policy_tag, "score_ground_value_100d00i"],
                errors="coerce",
            )
            .dropna()
            .to_numpy(dtype=float)
        )
        if policy_values.size == 0:
            continue
        values.append(policy_values)
        alpha = policy_alpha(policy_tag)
        positions.append(alpha)
        alphas.append(alpha)

    if not values:
        return

    fig, ax = plt.subplots(figsize=(8.7, 5.2), constrained_layout=True)
    box = ax.boxplot(
        values,
        positions=positions,
        widths=0.055,
        patch_artist=True,
        showmeans=True,
        boxprops={"linewidth": 1.1, "edgecolor": "0.15"},
        whiskerprops={"color": "0.25", "linewidth": 1.05},
        capprops={"color": "0.25", "linewidth": 1.05},
        medianprops={"color": "0.05", "linewidth": 1.4},
        meanprops={
            "marker": "D",
            "markerfacecolor": "white",
            "markeredgecolor": "0.05",
            "markersize": 5.5,
        },
        flierprops={
            "marker": "o",
            "markerfacecolor": "none",
            "markeredgecolor": "0.05",
            "markersize": 5.2,
            "linestyle": "none",
            "alpha": 0.85,
        },
    )
    for patch, alpha in zip(box["boxes"], alphas, strict=True):
        patch.set_facecolor(cmap(norm(alpha)))
        patch.set_alpha(0.72)

    for alpha, policy_values in zip(alphas, values, strict=True):
        jitter = np.linspace(-0.018, 0.018, len(policy_values))
        ax.scatter(
            np.full(len(policy_values), alpha) + jitter,
            policy_values,
            color=cmap(norm(alpha)),
            s=13,
            alpha=0.34,
            edgecolor="none",
            zorder=2,
        )

    ax.set_title("AMOS 2026 GAT Policies Scored With Common 100d00i Reward")
    ax.set_ylabel("Ground-value score")
    ax.set_xlim(-0.06, 1.06)
    ax.set_xticks(alphas)
    ax.set_xticklabels([f"{alpha:g}" for alpha in alphas])
    finish_axis(ax, r"Downlink reward weight $\alpha$")
    handles = [
        Line2D(
            [0],
            [0],
            marker="D",
            linestyle="none",
            markerfacecolor="white",
            markeredgecolor="0.05",
            markersize=5.5,
            label="Mean",
        ),
        Line2D(
            [0],
            [0],
            marker="o",
            linestyle="none",
            markerfacecolor="none",
            markeredgecolor="0.05",
            markersize=5.2,
            label="1.5-IQR outlier",
        ),
    ]
    ax.legend(handles=handles, loc="lower left", framealpha=0.9, fontsize=11)
    add_alpha_colorbar(fig, ax, norm, cmap, colorbar)
    save_figure(fig, out_dir, "ground_value_score_boxplot_common_100d00i")


