def annotate_alpha_points(ax: plt.Axes, rows: pd.DataFrame) -> None:
    offsets = {
        0.0: (16, 10),
        0.1: (18, 20),
        0.2: (-36, 8),
        0.3: (18, -18),
        0.4: (14, -30),
        0.5: (-44, 0),
        0.75: (-42, -28),
        1.0: (14, 16),
    }
    for _, row in rows.iterrows():
        alpha = float(row["alpha"])
        ax.annotate(
            format_alpha(alpha),
            (float(row["x_value"]), float(row["y_value"])),
            xytext=offsets.get(round(alpha, 2), (8, 8)),
            textcoords="offset points",
            fontsize=10,
            color="0.12",
            bbox={"facecolor": "white", "edgecolor": "none", "alpha": 0.76, "pad": 1.1},
            zorder=5,
        )


def plot_comparison_scatter(
    summary_100: pd.DataFrame,
    summary_200: pd.DataFrame,
    out_dir: Path,
    *,
    metric: str,
    label: str,
    stem: str,
    divisor: float = 1.0,
    reference_multiplier: float = 1.0,
) -> None:
    merged = summary_100[["policy_tag", "alpha", mean_col(summary_100, metric)]].merge(
        summary_200[["policy_tag", mean_col(summary_200, metric)]],
        on="policy_tag",
        suffixes=("_100", "_200"),
    )
    merged["x_value"] = merged[f"{metric}_mean_100"] / divisor
    merged["y_value"] = merged[f"{metric}_mean_200"] / divisor
    merged = merged[np.isfinite(merged["x_value"]) & np.isfinite(merged["y_value"])]

    cmap = plt.get_cmap("viridis")
    norm = Normalize(0.0, 1.0)
    fig, ax = plt.subplots(figsize=(7.95, 5.35), constrained_layout=True)
    ax.scatter(
        merged["x_value"],
        merged["y_value"],
        c=merged["alpha"],
        cmap=cmap,
        norm=norm,
        s=115,
        edgecolor="k",
        linewidth=0.75,
        zorder=3,
    )
    x_min = float(merged["x_value"].min())
    x_max = float(merged["x_value"].max())
    y_min = float(merged["y_value"].min())
    y_max = float(merged["y_value"].max())
    x_pad = 0.13 * max(x_max - x_min, 1.0)
    y_pad = 0.18 * max(y_max - y_min, 1.0)
    x0, x1 = x_min - x_pad, x_max + x_pad
    y0, y1 = y_min - y_pad, y_max + y_pad
    ax.set_xlim(x0, x1)
    ax.set_ylim(y0, y1)

    def add_reference(multiplier: float, label: str, linestyle: str, color: str) -> None:
        start = max(x0, y0 / multiplier)
        end = min(x1, y1 / multiplier)
        if start >= end:
            return
        xs = np.array([start, end])
        ys = multiplier * xs
        ax.plot(xs, ys, color=color, linestyle=linestyle, linewidth=1.1, alpha=0.65)
        ax.annotate(
            label,
            (xs[-1], ys[-1]),
            xytext=(-30, -18),
            textcoords="offset points",
            color=color,
        )

    add_reference(1.0, "1:1", "--", "0.28")
    if reference_multiplier != 1.0:
        add_reference(reference_multiplier, f"{reference_multiplier:g}x", ":", "0.45")
    annotate_alpha_points(ax, merged)
    ax.set_xlabel(f"{label}, 100 targets")
    ax.set_ylabel(f"{label}, 200 targets")
    ax.set_title(f"{label}: 100-target vs 200-target MC")
    finish_axis(ax)
    add_comparison_colorbar(fig, ax, norm, cmap)
    save_figure(fig, out_dir, stem)


def plot_reward_image_frontier(
    summary_100: pd.DataFrame,
    summary_200: pd.DataFrame,
    out_dir: Path,
) -> None:
    rows = []
    for label, n_targets, summary, marker in (
        ("100 targets", 100, summary_100, "o"),
        ("200 targets", 200, summary_200, "s"),
    ):
        for _, row in summary.iterrows():
            rows.append(
                {
                    "target_count": label,
                    "n_targets": n_targets,
                    "policy_tag": str(row["policy_tag"]),
                    "alpha": float(row["alpha"]),
                    "confirmed_per_target": row["confirmed_illuminated_images_mean"] / n_targets,
                    "ground_reward": row["score_ground_value_100d00i_mean"],
                    "marker": marker,
                }
            )
    data = pd.DataFrame(rows)
    cmap = plt.get_cmap("viridis")
    norm = Normalize(0.0, 1.0)
    fig, ax = plt.subplots(figsize=(8.35, 5.35), constrained_layout=True)
    for label, marker in (("100 targets", "o"), ("200 targets", "s")):
        subset = data[data["target_count"] == label]
        ax.plot(
            subset["confirmed_per_target"],
            subset["ground_reward"],
            color="0.22",
            linewidth=0.9,
            alpha=0.35,
            zorder=1,
        )
        ax.scatter(
            subset["confirmed_per_target"],
            subset["ground_reward"],
            c=subset["alpha"],
            cmap=cmap,
            norm=norm,
            marker=marker,
            s=105,
            edgecolor="k",
            linewidth=0.75,
            label=label,
            zorder=3,
        )
    ax.set_xlabel("Confirmed illuminated images per target")
    ax.set_ylabel("Ground reward")
    ax.set_title("Reward frontier normalized by catalog size")
    ax.legend(loc="upper left", framealpha=0.93)
    finish_axis(ax)
    add_comparison_colorbar(fig, ax, norm, cmap)
    save_figure(fig, out_dir, "comparison_reward_frontier_per_target_100_vs_200")


