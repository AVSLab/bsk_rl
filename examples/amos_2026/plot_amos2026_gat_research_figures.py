def plot_action_distribution(actions: pd.DataFrame, out_dir: Path) -> None:
    actions = normalize_policy_table(actions)
    actions["alpha"] = actions["policy_tag"].astype(str).map(policy_alpha)
    labels = ["image", "charge", "downlink", "desat"]
    x = actions["alpha"].to_numpy(dtype=float)
    width = 0.075

    fig, ax = plt.subplots(figsize=(8.1, 5.05), constrained_layout=True)
    bottom = np.zeros(len(actions))
    for label in labels:
        values = actions[f"{label}_actions"].to_numpy(dtype=float)
        ax.bar(
            x,
            values,
            bottom=bottom,
            width=width,
            color=ACTION_COLORS[label],
            edgecolor="0.15",
            linewidth=0.35,
            label=label.capitalize(),
            alpha=0.92,
        )
        bottom += values
    ax.set_ylabel("Action count across 100 seeds")
    ax.set_xlim(-0.06, 1.06)
    finish_axis(ax, r"Downlink reward weight $\alpha$")
    ax.legend(loc="lower center", ncol=4, framealpha=0.92)
    save_figure(fig, out_dir, "action_distribution_stacked_counts")

    # Fraction version is easier to compare behavior independent of episode length.
    totals = actions[[f"{label}_actions" for label in labels]].sum(axis=1).replace(0.0, np.nan)
    fig, ax = plt.subplots(figsize=(8.1, 5.05), constrained_layout=True)
    bottom = np.zeros(len(actions))
    for label in labels:
        values = (actions[f"{label}_actions"] / totals).to_numpy(dtype=float)
        ax.bar(
            x,
            values,
            bottom=bottom,
            width=width,
            color=ACTION_COLORS[label],
            edgecolor="0.15",
            linewidth=0.35,
            label=label.capitalize(),
            alpha=0.92,
        )
        bottom += np.nan_to_num(values)
    ax.set_ylabel("Action fraction")
    ax.set_xlim(-0.06, 1.06)
    ax.set_ylim(0, 1.0)
    finish_axis(ax, r"Downlink reward weight $\alpha$")
    ax.legend(loc="lower center", ncol=4, framealpha=0.92)
    save_figure(fig, out_dir, "action_distribution_stacked_fraction")


def plot_action_outcome_stacked_fraction(per_run: pd.DataFrame, out_dir: Path) -> None:
    required = {
        "policy_tag",
        "illuminated_images",
        "image_action_count_steps_csv",
        "downlink_action_count_steps_csv",
        "downlink_positive_reward_count",
        "charge_action_count_steps_csv",
        "desat_action_count_steps_csv",
    }
    if per_run.empty or not required.issubset(per_run.columns):
        return

    data = per_run[per_run["policy_tag"].isin(POLICY_ORDER)].copy()
    numeric_cols = sorted(required - {"policy_tag"})
    for col in numeric_cols:
        data[col] = pd.to_numeric(data[col], errors="coerce").fillna(0.0)

    grouped = data.groupby("policy_tag", observed=True)[numeric_cols].sum()
    rows = []
    for policy_tag in POLICY_ORDER:
        if policy_tag not in grouped.index:
            continue
        row = grouped.loc[policy_tag]
        image_actions = float(row["image_action_count_steps_csv"])
        downlink_actions = float(row["downlink_action_count_steps_csv"])
        total_actions = (
            image_actions
            + downlink_actions
            + float(row["charge_action_count_steps_csv"])
            + float(row["desat_action_count_steps_csv"])
        )
        if total_actions <= 0:
            continue
        illuminated = min(float(row["illuminated_images"]), image_actions)
        useful_downlinks = min(float(row["downlink_positive_reward_count"]), downlink_actions)
        rows.append(
            {
                "policy_tag": policy_tag,
                "alpha": policy_alpha(policy_tag),
                "image_illuminated": illuminated / total_actions,
                "image_not_illuminated": max(image_actions - illuminated, 0.0)
                / total_actions,
                "downlink_useful": useful_downlinks / total_actions,
                "downlink_no_value": max(downlink_actions - useful_downlinks, 0.0)
                / total_actions,
            }
        )

    outcome = pd.DataFrame(rows)
    if outcome.empty:
        return

    x = outcome["alpha"].to_numpy(dtype=float)
    series = [
        ("image_illuminated", "Image illuminated", "#2C7BB6"),
        ("image_not_illuminated", "Image not illuminated", "#A6CEE3"),
        ("downlink_useful", "Downlink useful", "#FDAE61"),
        ("downlink_no_value", "Downlink no value", "#D95F0E"),
    ]

    fig, ax = plt.subplots(figsize=(8.6, 5.25), constrained_layout=True)
    bottom = np.zeros(len(outcome))
    for metric, label, color in series:
        values = outcome[metric].to_numpy(dtype=float)
        ax.bar(
            x,
            values,
            bottom=bottom,
            width=0.075,
            color=color,
            edgecolor="0.15",
            linewidth=0.35,
            label=label,
            alpha=0.93,
        )
        bottom += values

    ax.set_ylabel("Action fraction")
    ax.set_xlim(-0.06, 1.06)
    ax.set_ylim(0, 1.0)
    finish_axis(ax, r"Downlink reward weight $\alpha$")
    ax.legend(
        loc="upper center",
        bbox_to_anchor=(0.5, -0.16),
        ncol=2,
        framealpha=0.93,
        columnspacing=1.5,
        handletextpad=0.55,
    )
    save_figure(fig, out_dir, "action_distribution_outcome_stacked_fraction")


