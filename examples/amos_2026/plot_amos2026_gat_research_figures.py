def policy_alpha(policy_tag: str) -> float:
    """Return downlink reward weight alpha from tags like 20d80i."""
    match = re.fullmatch(r"(\d+)d(\d+)i", policy_tag)
    if not match:
        raise ValueError(f"Cannot parse reward-mix tag as alpha: {policy_tag}")
    downlink_weight = float(match.group(1))
    imaging_weight = float(match.group(2))
    total = downlink_weight + imaging_weight
    if total <= 0:
        raise ValueError(f"Invalid reward-mix tag: {policy_tag}")
    return downlink_weight / total


